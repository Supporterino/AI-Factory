import { describe, expect, test } from "bun:test";
import { isGeneratedLockfile } from "../src/policy/paths.ts";
import { auditChanges, checkEdit, type SessionContext } from "../src/policy/scope.ts";

/** A task worktree; `touches` deliberately omits every lockfile below. */
const WT = "/ws/.factory/worktrees/add-x/app/1.1";

const IMPLEMENTER: SessionContext = {
  sessionId: "s",
  changeId: "add-x",
  role: "implementer",
  directory: WT,
  workspace: "/ws",
  repo: "app",
  task: "1.1",
  touches: ["app/**"],
  testGlobs: ["*.test.ts"],
};

const TESTER: SessionContext = {
  sessionId: "s",
  changeId: "add-x",
  role: "tester",
  directory: WT,
  workspace: "/ws",
  repo: "app",
  task: "1.1",
  testGlobs: ["*.test.ts"],
};

const LOCKFILES = [
  "Cargo.lock",
  "src-tauri/Cargo.lock",
  "packages/web/Cargo.lock",
  "bun.lock",
  "bun.lockb",
  "package-lock.json",
  "npm-shrinkwrap.json",
  "pnpm-lock.yaml",
  "yarn.lock",
  "poetry.lock",
  "uv.lock",
  "pdm.lock",
  "Pipfile.lock",
  "go.sum",
  "Podfile.lock",
  "Package.resolved",
  "Chart.lock",
  "composer.lock",
  "Gemfile.lock",
  "mix.lock",
  "pubspec.lock",
  "flake.lock",
  "deno.lock",
  "gradle.lockfile",
  "packages.lock.json",
];

describe("generated lockfiles are recognised at any depth", () => {
  test.each(LOCKFILES)("%s", (path) => {
    expect(isGeneratedLockfile(path)).toBe(true);
  });

  test("matching ignores case", () => {
    expect(isGeneratedLockfile("CARGO.LOCK")).toBe(true);
  });

  test.each([
    "Cargo.toml",
    "package.json",
    "go.mod",
    "pyproject.toml",
    "docs/Cargo.lock.md",
    "lockfile",
    "src/lockfile.rs",
  ])("%s is not a generated lockfile", (path) => {
    expect(isGeneratedLockfile(path)).toBe(false);
  });
});

describe("implementers may keep a regenerated lockfile even outside touches", () => {
  test.each(["Cargo.lock", "src-tauri/Cargo.lock", "frontend/pnpm-lock.yaml"])(
    "%s is allowed",
    (path) => {
      expect(checkEdit(IMPLEMENTER, path, () => true).allowed).toBe(true);
    },
  );

  test("approval is still required", () => {
    const verdict = checkEdit(IMPLEMENTER, "Cargo.lock", () => "change add-x is not approved");
    expect(verdict.allowed).toBe(false);
    if (!verdict.allowed) expect(verdict.reason).toContain("not approved");
  });

  test("the allowlist does not widen other files", () => {
    expect(checkEdit(IMPLEMENTER, "app/src/main.ts", () => true).allowed).toBe(true);
    expect(checkEdit(IMPLEMENTER, "src/main.ts", () => true).allowed).toBe(false);
    expect(checkEdit(IMPLEMENTER, "Cargo.toml", () => true).allowed).toBe(false);
  });

  test("the spec guard still wins over the lockfile name", () => {
    expect(checkEdit(IMPLEMENTER, "openspec/changes/add-x/Cargo.lock", () => true).allowed).toBe(
      false,
    );
  });
});

describe("testers may keep a lockfile regenerated by a test command", () => {
  test("allowed", () => {
    expect(checkEdit(TESTER, "Cargo.lock", () => true).allowed).toBe(true);
    expect(checkEdit(TESTER, "src-tauri/Cargo.lock", () => true).allowed).toBe(true);
  });

  test("their test-file scope still applies to everything else", () => {
    expect(checkEdit(TESTER, "app/src/main.ts", () => true).allowed).toBe(false);
  });
});

describe("the post-session audit accepts regenerated lockfiles", () => {
  test("lockfiles are not violations", () => {
    expect(auditChanges(IMPLEMENTER, ["Cargo.lock", "src-tauri/Cargo.lock"], true)).toEqual([]);
  });

  test("other out-of-scope files are still reported", () => {
    expect(auditChanges(IMPLEMENTER, ["src/main.ts"], true).map((v) => v.path)).toEqual([
      "src/main.ts",
    ]);
  });
});
